import { describe, expect, it } from "vitest";
import { filterFiles, hasGeneratedHeader, pathSkipReason } from "./filter";
import type { FileChange } from "./schema";

const file = (filename: string, over: Partial<FileChange> = {}): FileChange => ({
  filename, status: "modified", additions: 1, deletions: 0, patch: "@@ -10,1 +10,2 @@\n x\n+y", ...over,
});

describe("pathSkipReason", () => {
  it.each([
    ["package-lock.json", "lockfile"],
    ["apps/web/yarn.lock", "lockfile"],
    ["pnpm-lock.yaml", "lockfile"],
    ["go.sum", "lockfile"],
    ["dist/index.js", "in dist/"],
    ["packages/ui/build/out.js", "in build/"],
    [".next/server/page.js", "in .next/"],
    ["node_modules/react/index.js", "in node_modules/"],
    ["vendor/lib/x.go", "in vendor/"],
    ["public/app.min.js", "minified"],
    ["styles/site.MIN.css", "minified"],
    ["dist2/app.js.map", "source map"],
    ["public/logo.PNG", "image"],
    ["icons/arrow.svg", "image"],
    ["fonts/inter.woff2", "font"],
  ])("skips %s (%s)", (path, reason) => {
    expect(pathSkipReason(path)).toBe(reason);
  });

  it.each(["src/index.ts", "src/build.ts", "docs/distribution.md", "src/vendors.ts", "README", "src/lock.ts", "src/map.ts"])(
    "keeps %s",
    (path) => {
      expect(pathSkipReason(path)).toBeNull();
    },
  );
});

describe("hasGeneratedHeader", () => {
  it("finds @generated in the first lines of a new file", () => {
    expect(hasGeneratedHeader("@@ -0,0 +1,3 @@\n+// @generated by protoc\n+export const a = 1;\n+export const b = 2;")).toBe(true);
  });
  it("finds it in context lines of an edit near the top", () => {
    expect(hasGeneratedHeader("@@ -1,3 +1,3 @@\n /* @generated */\n-a\n+b")).toBe(true);
  });
  it("ignores @generated further down the file", () => {
    const lines = ["@@ -0,0 +1,7 @@", ...Array.from({ length: 6 }, (_, i) => `+line ${i}`), "+// @generated"];
    expect(hasGeneratedHeader(lines.join("\n"))).toBe(false);
  });
  it("can't see the top of the file when the patch starts lower", () => {
    expect(hasGeneratedHeader("@@ -40,1 +40,1 @@\n-a\n+// @generated")).toBe(false);
  });
  it("is false for an empty patch", () => {
    expect(hasGeneratedHeader("")).toBe(false);
  });
});

describe("filterFiles", () => {
  it("keeps normal source files and gives every skipped file a reason", () => {
    const result = filterFiles([
      file("src/a.ts"),
      file("package-lock.json"),
      file("src/old.ts", { status: "removed", patch: "@@ -1 +0,0 @@\n-x" }),
      file("logo.png", { patch: undefined }),
      file("src/moved.ts", { status: "renamed", patch: undefined }),
      file("src/gen.ts", { status: "added", patch: "@@ -0,0 +1,2 @@\n+// @generated\n+x" }),
      file("src/renamed-and-edited.ts", { status: "renamed" }),
    ]);
    expect(result.kept.map((f) => f.filename)).toEqual(["src/a.ts", "src/renamed-and-edited.ts"]);
    expect(result.skipped).toEqual([
      { file: "package-lock.json", reason: "lockfile" },
      { file: "src/old.ts", reason: "removed file" },
      { file: "logo.png", reason: "no patch (binary, too large for GitHub, or rename only)" },
      { file: "src/moved.ts", reason: "no patch (binary, too large for GitHub, or rename only)" },
      { file: "src/gen.ts", reason: "generated (@generated header)" },
    ]);
  });

  it("treats an empty-string patch as no patch", () => {
    expect(filterFiles([file("src/a.ts", { patch: "" })]).skipped[0]?.reason).toMatch(/^no patch/);
  });

  it("returns empty lists for no files", () => {
    expect(filterFiles([])).toEqual({ kept: [], skipped: [] });
  });
});
